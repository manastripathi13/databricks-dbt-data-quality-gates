"""Summarise a demo run: data quality SLA before vs after gates, quarantine, revenue KPIs, lineage.

Prints to the terminal and writes docs/RESULTS.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.spark import get_spark  # noqa: E402


def lineage(manifest_path: Path) -> list[str]:
    """For each BI exposure, list every upstream dbt model and source (from dbt's manifest)."""
    m = json.loads(manifest_path.read_text())
    parents = m["parent_map"]

    def walk(node: str, seen: set[str]) -> set[str]:
        for p in parents.get(node, []):
            if p not in seen:
                seen.add(p)
                walk(p, seen)
        return seen

    lines = []
    for uid, exp in sorted(m["exposures"].items()):
        ups = sorted(u.split(".", 2)[-1] for u in walk(uid, set()) if u.startswith(("model.", "source.")))
        lines.append(f"- **{exp['label']}** ({exp['owner']['name']}) ← " + ", ".join(f"`{u}`" for u in ups))
    return lines


def main() -> None:
    spark = get_spark("report")
    runs = [json.loads(x) for x in (ROOT / "data" / "run_log.jsonl").read_text().splitlines()]
    dq = spark.sql("""
        select run_date, layer, met_quality_bar, critical_failures, pass_rate_pct
        from gold.rpt_data_quality_daily order by run_date, layer""").collect()
    raw = {r.run_date: r for r in dq if r.layer == "raw"}
    days = len(runs)
    raw_ok = sum(1 for r in runs if raw.get(r["run_date"]) and raw[r["run_date"]].met_quality_bar)
    gated_ok = sum(1 for r in runs if r["gold_refreshed"])

    quarantine = {}
    for t in ["quarantine_usage", "quarantine_subscriptions", "quarantine_opportunities"]:
        for row in spark.sql(f"select explode(_failed_rules) rule, count(*) n from revenue.{t} group by 1").collect():
            quarantine[f"{t.replace('quarantine_', '')}.{row.rule}"] = row.n
    dupes = spark.sql("select (select count(*) from revenue.bronze_usage) - (select count(*) from revenue.silver_usage) "
                      "- (select count(*) from revenue.quarantine_usage) as n").collect()[0].n

    arr = spark.sql("""select as_of_date, round(sum(arr_usd)) arr, sum(paying_customers) cust from gold.rpt_arr_by_product
                       group by 1 order by 1""").collect()
    nrr = spark.table("gold.rpt_net_revenue_retention").collect()[0]
    health = spark.sql("select health_status, count(*) n from gold.rpt_customer_health group by 1 order by 1").collect()
    overage = spark.sql("select round(sum(overage_revenue_usd)) usd, count_if(overage_revenue_usd > 0) subs from gold.rpt_usage_overage").collect()[0]

    md = ["# Results of the last local run", "", "Generated by `scripts/report.py`. Synthetic data, 10 business days.", "",
          "## Data quality SLA", "",
          "SLA = share of daily refreshes where the data reaching dashboards passed every **critical** check.", "",
          "| | Days meeting SLA | SLA |", "|---|---|---|",
          f"| Without gates (raw drops straight to dashboards) | {raw_ok} / {days} | {100 * raw_ok / days:.0f}% |",
          f"| With quarantine + Great Expectations gate | {gated_ok} / {days} | {100 * gated_ok / days:.0f}% |", "",
          "| Date | Raw drop | Silver gate | Gold refreshed |", "|---|---|---|---|"]
    for r in runs:
        rr = raw.get(r["run_date"])
        md.append(f"| {r['run_date']} | {'pass' if rr and rr.met_quality_bar else f'FAIL ({rr.critical_failures if rr else '?'} critical)'} "
                  f"| {'pass' if r['gate_passed'] else 'BLOCK'} | {'yes' if r['gold_refreshed'] else 'no'} |")
    md += ["", "## Bad rows stopped before Gold", "", "| Dataset.rule | Rows quarantined |", "|---|---|"]
    md += [f"| {k} | {v} |" for k, v in sorted(quarantine.items())]
    md += [f"| usage duplicate events collapsed | {dupes} |", "",
           "## Revenue KPIs (Gold)", "",
           f"- ARR on {arr[0].as_of_date}: ${arr[0].arr:,.0f} → on {arr[-1].as_of_date}: ${arr[-1].arr:,.0f}",
           f"- Net revenue retention {nrr.period_start} to {nrr.period_end}: {nrr.net_revenue_retention_pct}% "
           f"(gross {nrr.gross_revenue_retention_pct}%), churned customers: {nrr.churned_customers}",
           f"- Month-to-date overage revenue: ${overage.usd:,.0f} across {overage.subs} subscriptions",
           "- Customer health: " + ", ".join(f"{h.health_status} {h.n}" for h in health), "",
           "## Lineage: every BI consumer traced back to its sources", ""]
    md += lineage(ROOT / "dbt" / "target" / "manifest.json")
    out = ROOT / "docs" / "RESULTS.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
